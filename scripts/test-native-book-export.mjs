import assert from "node:assert/strict";
import { readFileSync } from "node:fs";

const notebook = readFileSync(
  new URL("../android/app/src/main/java/com/anwar/mofakira/NativeNotebookActivity.kt", import.meta.url),
  "utf8"
);
const manifest = readFileSync(
  new URL("../android/app/src/main/AndroidManifest.xml", import.meta.url),
  "utf8"
);

assert.match(notebook, /private fun showArchiveMenu\(\)/,
  "The native archive menu remains present.");
assert.match(notebook, /إنشاء كتاب PDF من الأعمال/,
  "The native archive offers book creation.");
assert.match(notebook, /private fun showNativeBookExportOptions\(\)/,
  "The user can choose which saved works to include.");
assert.match(notebook, /كل الأعمال المحفوظة/);
assert.match(notebook, /القصائد فقط/);
assert.match(notebook, /النصوص والأفكار/);
assert.match(notebook, /notes\.filter \{ it\.type == "poem" \}/);
assert.match(notebook, /notes\.filter \{ it\.type == "text" \|\| it\.type == "idea" \}/);

assert.match(notebook, /private fun buildNativeBookPdf\(/,
  "The PDF is generated by the native Android implementation.");
assert.match(notebook, /PdfDocument\(\)/);
assert.match(notebook, /PdfDocument\.PageInfo\.Builder\(pageWidth, pageHeight, pageNumber\)/);
assert.match(notebook, /StaticLayout\.Builder/);
assert.match(notebook, /TextDirectionHeuristics\.RTL/,
  "Arabic book text is laid out right-to-left.");
assert.match(notebook, /richHtmlToText\(note\.richHtml\)/,
  "Saved rich notebook content is included in the export.");
assert.match(notebook, /note\.text/,
  "Plain-text notebook content is included in the export.");
assert.match(notebook, /note\.title/);
assert.match(notebook, /note\.updatedAt/);
assert.match(notebook, /MAX_BOOK_PDF_CHARACTERS/);
assert.match(notebook, /MAX_BOOK_PDF_PAGES/);
assert.match(notebook, /MAX_BOOK_PDF_BYTES/);

assert.match(notebook, /Thread\(\{/,
  "PDF rendering happens off the UI thread.");
assert.match(notebook, /Intent\.ACTION_CREATE_DOCUMENT/,
  "The generated file is saved through Android's document picker.");
assert.match(notebook, /type = "application\/pdf"/);
assert.match(notebook, /REQUEST_BOOK_PDF_EXPORT/);
assert.match(notebook, /private fun persistNativeBookPdf\(/);
assert.match(notebook, /readBack\.contentEquals\(bytes\)/,
  "The saved PDF is read back and byte-verified before success is reported.");
assert.match(notebook, /readLimited\(input, MAX_BOOK_PDF_BYTES\)/);
assert.match(notebook, /pendingBookPdf = null/,
  "Temporary PDF bytes are cleared after save or cancellation.");

const activityResult = notebook.slice(
  notebook.indexOf("override fun onActivityResult"),
  notebook.indexOf("private fun showOptionPicker")
);
assert.match(activityResult, /REQUEST_BOOK_PDF_EXPORT -> persistNativeBookPdf\(uri\)/);
assert.match(activityResult, /REQUEST_BOOK_PDF_EXPORT\) pendingBookPdf = null/);

assert.match(notebook, /private const val REQUEST_BOOK_PDF_EXPORT = 7303/);
assert.match(notebook, /private const val BOOK_PDF_PAGE_WIDTH = 595/);
assert.match(notebook, /private const val BOOK_PDF_PAGE_HEIGHT = 842/);
assert.doesNotMatch(notebook, /android\.webkit\.WebView|JavascriptInterface/,
  "Book generation is native Android code, not a WebView or JavaScript bridge.");
assert.match(manifest, /android:name="\.NativeNotebookActivity"/,
  "The encrypted native notebook activity remains registered.");

console.log("Native notebook PDF book export and verified Android document-save checks passed.");
